"""Incremental detokenization must never re-send streamed text.

When a step's decoded text ends inside a character (a byte-level BPE splits rare
characters and emoji across tokens), `DetokenizeState.step` sends only the
printable prefix that `find_printable_text` picks and records it in
`sent_offset`. That heuristic is stateless and its result is not monotonic: a
later step can yield a shorter prefix than an earlier one. If `sent_offset`
follows it backwards, the next clean step under-counts `pending` and re-sends
text the client already has.

Reachable shapes, all in the heuristic's last-space branch:

1. collapse to "" -- "你好，" + a dangling byte yields "" after "你" + a dangling
   byte yielded "你": the fullwidth comma is not classified as CJK and there is
   no space to fall back to;
2. retreat to a space -- "A 世好a" + a dangling byte yields "A " after "A 世" +
   a dangling byte yielded "A 世";
3. a non-CJK symbol after CJK text, as in "部署完成✅🚀": the emoji are split
   across tokens and are not CJK either.

Ported from sgl-project/sglang#41058 to the DetokenizeState API. The tests drive
the real DetokenizerManager.handle_batch_token_id_out with a byte-level stub
tokenizer, so there is no IPC and no tokenizer download.
"""

import unittest
from array import array
from unittest import mock

from sglang.test.ci.ci_register import register_cpu_ci
from sglang.test.test_utils import CustomTestCase, maybe_stub_sgl_kernel

maybe_stub_sgl_kernel()

from sglang.srt.managers import incremental_detokenize
from sglang.srt.managers.detokenizer_manager import DetokenizerManager
from sglang.srt.managers.incremental_detokenize import (
    DetokenizeHeader,
    DetokenizeStateTable,
)
from sglang.srt.managers.io_struct import BatchTokenIDOutput, flatten_output_ids
from sglang.srt.runtime_context import get_context

register_cpu_ci(est_time=5, suite="base-a-test-cpu")

# Ids from TEXT_TOKEN up decode to the byte (id - TEXT_TOKEN), so a multi-byte
# character can arrive split across tokens and decode to U+FFFD until its last
# byte lands. The prompt tail uses the same encoding.
TEXT_TOKEN = 256
PROMPT_TAIL = b"Q: "

# Each case: the generated bytes split into engine steps. The first two steps
# end mid-character; a final empty step finishes the request.
COLLAPSE = "你好，世".encode()
COLLAPSE_STEPS = [COLLAPSE[:5], COLLAPSE[5:10], COLLAPSE[10:], b""]
SPACE = "A 世好a世".encode()
SPACE_STEPS = [SPACE[:6], SPACE[6:10], SPACE[10:], b""]
EMOJI = "部署完成✅🚀上线".encode()
EMOJI_STEPS = [EMOJI[:13], EMOJI[13:16], EMOJI[16:], b""]
RETREAT_CASES = {
    "collapse": (COLLAPSE_STEPS, "你好，世"),
    "space": (SPACE_STEPS, "A 世好a世"),
    "emoji": (EMOJI_STEPS, "部署完成✅🚀上线"),
}


class _ByteTokenizer:
    """Byte-level stub: one token per byte, decoded as UTF-8."""

    is_fast = True

    def decode(self, ids, skip_special_tokens=True, spaces_between_special_tokens=True):
        return bytes(i - TEXT_TOKEN for i in ids).decode("utf-8", errors="replace")

    def batch_decode(self, ids_list, **kwargs):
        return [self.decode(ids, **kwargs) for ids in ids_list]


def _ids(data):
    return [TEXT_TOKEN + b for b in data]


def _detokenizer(disable_tokenizer_batch_decode):
    detok = DetokenizerManager.__new__(DetokenizerManager)
    detok.output_updates = None
    detok.tokenizer = _ByteTokenizer()
    detok.vocab_size = None
    detok.detokenize_state_table = DetokenizeStateTable(capacity=4)
    detok.disable_tokenizer_batch_decode = disable_tokenizer_batch_decode
    detok.is_tool_call_parser_gpt_oss = False
    detok.tool_close_token_ids = frozenset()
    return detok


def _output(ids, header, finished, completion_tokens):
    output_ids_flat, output_ids_offsets = flatten_output_ids([ids])
    return BatchTokenIDOutput(
        rids=["r"],
        finished_reasons=[{"type": "length"} if finished else None],
        output_ids_flat=output_ids_flat,
        output_ids_offsets=output_ids_offsets,
        detokenize_headers=[header] if header is not None else None,
        http_worker_ipcs=["worker-a"] if finished else None,
        reasoning_tokens=[0],
        completion_tokens=[completion_tokens],
        input_token_logprobs_val=None,
        input_token_logprobs_idx=None,
        output_token_logprobs_val=None,
        output_token_logprobs_idx=None,
        input_top_logprobs_val=None,
        input_top_logprobs_idx=None,
        output_top_logprobs_val=None,
        output_top_logprobs_idx=None,
        input_token_ids_logprobs_val=None,
        input_token_ids_logprobs_idx=None,
        output_token_ids_logprobs_val=None,
        output_token_ids_logprobs_idx=None,
        output_token_entropy_val=None,
        output_token_sampling_mask=None,
        output_hidden_states=None,
        routed_experts=None,
        indexer_topk=None,
        placeholder_tokens_idx=None,
        placeholder_tokens_val=None,
    )


def _stream(steps, *, disable_tokenizer_batch_decode=False, on_printable=None):
    """Run one request through the detokenizer, one engine step per entry of
    `steps`; the last entry finishes it. Returns the text the client receives
    and `sent_offset` after each unfinished step.

    `on_printable(state, text, printable)` is called whenever the incomplete-
    character branch asks find_printable_text, before `sent_offset` changes."""
    detok = _detokenizer(disable_tokenizer_batch_decode)
    header = DetokenizeHeader(
        prompt_tail_ids=array("q", _ids(PROMPT_TAIL)),
        skip_special_tokens=True,
        spaces_between_special_tokens=True,
        no_stop_trim=False,
        http_worker_ipc="worker-a",
    )
    real = incremental_detokenize.find_printable_text

    def spy(text):
        printable = real(text)
        if on_printable is not None:
            on_printable(detok.detokenize_state_table.get("r"), text, printable)
        return printable

    texts, offsets, completion_tokens = [], [], 0
    with mock.patch.object(incremental_detokenize, "find_printable_text", spy):
        for i, chunk in enumerate(steps):
            finished = i == len(steps) - 1
            ids = _ids(chunk)
            completion_tokens += len(ids)
            out = detok.handle_batch_token_id_out(
                _output(ids, header if i == 0 else None, finished, completion_tokens)
            )
            texts += out.output_strs
            state = detok.detokenize_state_table.get("r")
            if state is not None:
                offsets.append(state.sent_offset)
    return "".join(texts), offsets


class TestIncrementalDetokenizeSentOffset(CustomTestCase):
    def setUp(self) -> None:
        self.enterContext(get_context().override_server_args(kv_canary="none"))

    def test_a_shrinking_printable_prefix_does_not_resend_text(self):
        for name, (steps, expected) in RETREAT_CASES.items():
            for batch_decode_off in (False, True):
                with self.subTest(case=name, disable_batch_decode=batch_decode_off):
                    text, _ = _stream(
                        steps, disable_tokenizer_batch_decode=batch_decode_off
                    )
                    self.assertEqual(text, expected)

    def test_sent_offset_never_retreats(self):
        for name, (steps, _) in RETREAT_CASES.items():
            with self.subTest(case=name):
                _, offsets = _stream(steps)
                self.assertEqual(offsets, sorted(offsets))

    def test_each_case_reaches_a_shrinking_printable_prefix(self):
        """Pins that the cases above hit the branch the fix guards: a printable
        prefix shorter than what was already sent."""
        for name, (steps, _) in RETREAT_CASES.items():
            seen = []

            def record(state, text, printable):
                seen.append(state.sent_offset > state.decoded_text_len + len(printable))

            with self.subTest(case=name):
                _stream(steps, on_printable=record)
                self.assertIn(True, seen)
                self.assertIn(False, seen)

    def test_plain_ascii_stream_is_unchanged(self):
        text, _ = _stream([b"hello ", b"world ", b"bye", b""])
        self.assertEqual(text, "hello world bye")

    def test_a_character_split_once_is_sent_once(self):
        text, _ = _stream(["你好".encode()[:4], "你好".encode()[4:], b""])
        self.assertEqual(text, "你好")


